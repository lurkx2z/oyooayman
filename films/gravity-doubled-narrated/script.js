const GN_CLIP = Object.fromEntries(GN.clips.map((c) => [c.id, c]));
// word i of clip id: { text, start, end } (film seconds)
function gnW(id, i) { return GN_CLIP[id].words[i]; }
const NA = GN_CLIP['a-opening'], NB = GN_CLIP['b-cafe'], NC = GN_CLIP['c-falling'], ND = GN_CLIP['d-outside'], NE = GN_CLIP['e-ending'];

// ---------------------------------------------------------------------------------------------------------------------
// THE BEATS (film seconds). Every other file keys off these.
