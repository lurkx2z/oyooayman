const GB = {};
// SCENE 1 — the hook (café, the slow push toward his cup)
GB.g = gnW('a-opening', 4).start + 0.14;          // ★ "dou-BLED": gravity 1.0 → 2.0 g (gbG(t) is the one value for physics, HUD, sound)
// SCENE 2 — the heavier cup (narration B)
GB.room = NB.start - 0.15;                         // cut: the whole room, "nothing looks different"
GB.reachCut = gnW('b-cafe', 5).start - 0.12;       // "But that coffee cup?" → the medium on him and his cup
GB.reach = [gnW('b-cafe', 7).start - 0.1, gnW('b-cafe', 9).start];   // the right hand travels to the handle
GB.grip = GB.reach[1];                             // fingers close round the handle ("Same mass") — before the cup moves
GB.handCU = gnW('b-cafe', 9).start - 0.25;         // cut: close-up of the hand on the handle
GB.lift = gnW('b-cafe', 13).start;                 // "weight": the pull starts (the cup sticks for a beat, then rises)
// SCENE 3 — no narration: he finishes the struggle; the cup is down before anything cuts away
GB.faceCut = GB.lift + 2.3;                        // cut: hands + face (one continuous take of the hold and the set-down)
GB.top = GB.lift + 2.7;                            // the cup reaches its highest point (~10 cm), trembling
GB.lower = GB.top + 1.5;                           // he starts to lower it, carefully
GB.down = GB.lower + 1.8;                          // ★ touch-down on the saucer
GB.letGo = GB.down + 0.4;                          // fingers open, the hand lifts away
// SCENE 4 — the falling experiment (narration C)
GB.exp = NC.start - 0.2;                           // cut: the experiment (match cut: his cup → the cup in the release clamp)
GB.wideExp = gnW('c-falling', 8).start - 0.3;      // "From one meter": pull back to both lanes + the metre stick
GB.oneM = [gnW('c-falling', 8).start, gnW('c-falling', 10).end];
GB.lane1 = [gnW('c-falling', 15).start, gnW('c-falling', 22).end];   // "zero point four five seconds at normal gravity"
GB.lane2 = [gnW('c-falling', 24).start, gnW('c-falling', 31).end];   // "zero point three two seconds at double gravity"
// SCENE 5 — no narration: the drop, the impacts, a slow-motion replay, the hold
GB.drop = NC.speechEnd + 1.25;                     // the clamps open (both lanes at the same instant)
GB.replay = GB.drop + 1.8;                         // slow-motion replay starts (same shot)
GB.replayRate = 0.2;                               // 5× slower
GB.replayFrom = -0.08;                             // replay covers experiment time −0.08 … +0.52 s (both impacts)
GB.replayTo = 0.52;
GB.replayEnd = GB.replay + (GB.replayTo - GB.replayFrom) / GB.replayRate;   // then real time again: the shards settle, a held result
// SCENE 6 — outside (narration D)
GB.out = ND.start - 0.35;                          // cut outside: the man on the bench tries to rise
GB.rise1 = [ND.start + 0.6, gnW('d-outside', 8).end + 0.2];   // first attempt: he pushes up… and sinks back
GB.carCU = gnW('d-outside', 9).start - 0.25;       // "Even parked cars": the wheel close-up (spring, 1 g ride height)
// SCENE 7 — no narration: he finally stands (braced on the car's wing), a slow step; a second person fights to stay up
GB.world = ND.speechEnd + 0.3;                     // cut: the medium-wide (bench, car, him)
GB.rise2 = [GB.world + 0.5, GB.world + 2.9];       // the second attempt: hand on the car, he comes up (the car dips under it)
GB.step = [GB.world + 3.6, GB.world + 5.2];        // a slow, heavy step away from the car (the car rocks back up)
GB.wide2 = GB.world + 4.9;                         // cut: the wide hold (her struggle, him, the car, the fountain)
// SCENE 8 — the ending (narration E)
GB.pull = NE.start - 0.6;                          // the crane pulls back into the atmospheric wide
GB.end = Math.round((NE.end + 2.1) * 30) / 30;     // the last music note decays; fade at the very end
GB.fade = [GB.end - 1.3, GB.end];

