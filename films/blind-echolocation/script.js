const BN_CLIP = Object.fromEntries(BN.clips.map((c) => [c.scene, c]));
const BN_SC = Object.fromEntries(BN.scenes.map((s) => [s.n, s]));
// word i of scene n: { text, start, end } (film seconds)
function bnW(n, i) { const w = BN_CLIP[n].words; return w[i < 0 ? w.length + i : i]; }
// the first word of scene n (after word index `from`) whose text starts with `txt` (case-insensitive, punctuation ignored)
function bnF(n, txt, from = 0) {
  const k = txt.toLowerCase(), ws = BN_CLIP[n].words;
  for (let i = from; i < ws.length; i++) if (ws[i].text.toLowerCase().replace(/[^a-z0-9']/g, '').startsWith(k)) return ws[i];
  throw new Error(`bnF: "${txt}" not found in scene ${n}`);
}

