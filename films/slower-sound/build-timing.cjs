/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if sound kept getting slower and couldn't stop?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/slower-sound/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions' words (each word gets an anchor time inside its caption), so changing a pause or a line
   here re-times the whole film. Writes timing.js (window.SST). Pure data: no clock, no randomness.
   Retention (the owner's note, 2026-10-25): short pauses, a new thing to see every few seconds; the long pauses are
   only where the picture itself is the reveal (the sky's colours, the fire, the afterglow).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 1.0
const PAUSE = {
  open: 0.5, title: 0.9, seven: 0.9, bird: 0.8, plane: 1.0, boom: 1.0, carpet: 1.0,
  eight: 1.2, throat: 0.8, kettle: 1.0, radio: 1.0,
  nine: 1.2, spoon: 0.8, ten: 1.2, motorway: 1.2,
  eleven: 1.2, siren: 0.8, silent: 1.6, after: 0.8, backwards: 1.2, noon: 1.4, ball: 1.0, flying: 1.2, horizon: 0.6,
  one: 1.4, two: 1.4, ears: 1.0, three: 1.3, popcorn: 0.6,
  four: 1.4, clap: 1.0, earbuds: 1.2, five: 1.2, hum: 1.0,
  storm: 1.4, eight2: 1.4, box: 1.4, walkinto: 1.2, wait: 0.9, arrives: 1.0,
  midnight: 1.6, stop: 1.0, last: 1.2,
  real: 1.8, real2: 0.6, real3: 0.8, real4: 0.8, real5: 0.9, question: 1.2,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'boom:1': 1.2, 'siren:2': 0.6, 'after:1': 0.4, 'backwards:1': 1.0, 'noon:2': 2.4, 'ball:1': 1.0, 'one:3': 1.2, 'two:2': 0.6,
  'popcorn:1': 0.2, 'clap:1': 0.8, 'five:2': 0.9, 'storm:2': 1.0, 'storm:3': 0.6, 'box:3': 2.2, 'wait:1': 0.6, 'arrives:1': 0.5, 'last:2': 1.2, 'stop:1': 0.3,
};
const SECTION_OF = { open: 1, title: 1, seven: 2, nine: 3, eleven: 4, four: 5, storm: 6, midnight: 7, real: 8 };
const GAP = 0.65;                     // between captions inside a beat
const TAIL = 4.4;                     // the question held, then the cut
const hold = (s) => Math.min(4.2, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.4;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 1.0));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  groups.push({ id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps });
  t = groups[groups.length - 1].end;
});
const SST = { duration: r3(t + TAIL), groups };
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if sound kept getting slower and couldn't stop?", generated by build-timing.cjs from
   CAPTIONS.md. Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.SST = ${JSON.stringify(SST)};
`);
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${g.first.toFixed(2).padStart(7)} → ${g.end.toFixed(2).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${SST.duration} s (${Math.floor(SST.duration / 60)}:${String(Math.round(SST.duration % 60)).padStart(2, '0')})`);
