/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if everything kept shrinking and couldn't stop?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/sound-faster-light/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions (and so does the story clock: which second after 6:49 AM we are watching), so changing a
   pause or a line here re-times the whole film. Writes timing.js (window.EKT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture or the sound is the reveal (the tent ripping, the silence, the shadow, the speck, the black sky).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const PAUSE = {
  title: 0.05, start: 0.7, out: 2.0, rule: 2.6, leo: 2.0, voice: 1.2, weight: 1.8, neighbours: 2.4, hush: 2.6, sunrise: 4.0, shadow: 2.8,
  peaks: 3.0, air: 2.6, escape: 1.6, curve: 3.6, sky: 3.0, lift: 3.0, house: 2.4, ball: 3.0, end: 2.6, question: 2.6,
  rumble: 1.4, quiet: 3.0, plane: 2.6, moon: 3.0,
};
const EXTRA = {
  'start:1': 0.3, 'start:2': 0.4, 'out:1': 2.0, 'rule:1': 0.4, 'rule:2': 0.4, 'leo:1': 1.2, 'voice:1': 0.8, 'weight:1': 0.6, 'weight:2': 2.0,
  'neighbours:1': 0.8, 'neighbours:2': 0.8, 'hush:1': 1.0, 'hush:2': 1.2, 'shadow:1': 2.6, 'peaks:1': 0.8, 'air:1': 0.6, 'air:2': 0.8,
  'air:3': 1.0, 'air:4': 1.2, 'escape:1': 0.8, 'sky:1': 2.0, 'end:1': 1.6, 'rumble:1': 0.8, 'quiet:1': 3.0, 'house:1': 1.0, 'house:2': 1.0,
};
const SECTION_OF = { title: 1, neighbours: 2, peaks: 3, lift: 4 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = 1.8;                    // the question holds on the last shot, then a hard cut
const hold = (s) => Math.min(5.4, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const EKT = { duration: r3(t + TAIL), groups };
{ const g = groups[groups.length - 1], c = g.caps[g.caps.length - 1]; c.hide = g.end = EKT.duration; }   // (the question stays up to the last frame)
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if everything kept shrinking and couldn't stop?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.EKT = ${JSON.stringify(EKT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${EKT.duration} s (${Math.floor(EKT.duration / 60)}:${String(Math.round(EKT.duration % 60)).padStart(2, '0')})`);
