/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if the ocean kept rising and couldn't stop?"
   (voiceless, like the Slower light film: captions, the HUD, Isla's texts and the sound).
     node films/ocean-rising/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions (and so does the story clock: which second after 6:42:00 PM we are watching), so changing a
   pause or a line here re-times the whole film. Writes timing.js (window.OCT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture or the sound is the reveal (the boat going under, the texts, the burst, the stairs, the lamp).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 0.8
const PAUSE = {
  title: 0.05, start: 0.4, boat: 1.2, phone: 1.4, rule: 1.4, height: 1.4, lichen: 1.2, radio: 1.6, bell: 1.4, world: 1.6, fog: 3.8, cottage: 1.8, island: 1.8,
  door: 1.8, burst: 2.6, dark: 2.0, stairs: 2.0, town: 2.0, lights: 2.2, ship: 1.8, ice: 1.4, hill: 2.0, lie: 2.4, watch: 1.8, gallery: 2.4, lamp: 2.2, roof: 2.4, question: 2.2,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.4, 'start:2': 0.4, 'boat:1': 1.6, 'boat:2': 1.4, 'rule:1': 0.4, 'rule:2': 0.6, 'height:1': 0.6, 'phone:1': 2.2, 'radio:1': 0.8, 'world:1': 1.2, 'island:1': 1.6,
  'fog:1': 1.6, 'cottage:1': 1.4, 'door:1': 1.6, 'dark:1': 1.2, 'stairs:1': 1.4, 'town:1': 1.8, 'lights:1': 1.6, 'ship:1': 1.0, 'ship:2': 0.8, 'hill:1': 1.6, 'watch:1': 1.4,
  'lamp:1': 2.0, 'roof:1': 1.8,
};
const SECTION_OF = { title: 1, island: 2, burst: 3, gallery: 4 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = 2.4;                    // the question holds, then a hard cut on the last frame
const hold = (s) => Math.min(5.4, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const OCT = { duration: r3(t + TAIL), groups };
{ const g = groups[groups.length - 1], c = g.caps[g.caps.length - 1]; c.hide = g.end = OCT.duration; }   // (the question stays up to the last frame)
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if the ocean kept rising and couldn\'t stop?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.OCT = ${JSON.stringify(OCT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${OCT.duration} s (${Math.floor(OCT.duration / 60)}:${String(Math.round(OCT.duration % 60)).padStart(2, '0')})`);
