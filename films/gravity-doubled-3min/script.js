// gravity in g (1 → 2), a very short ramp so it reads as instant but stays smooth for springs
function gbG(t) { return 1 + MathX.smooth(t, GB.g, GB.g + 0.12); }
function gbSince(t) { return t - GB.g; }

// the experiment clock: seconds since the clamps opened (real time, then the slow replay, then real time again)
function gbExpT(t) {
  if (t < GB.replay) return t - GB.drop;
  if (t < GB.replayEnd) return GB.replayFrom + (t - GB.replay) * GB.replayRate;
  return GB.replayTo + (t - GB.replayEnd);
}
function gbInReplay(t) { return t >= GB.replay && t < GB.replayEnd; }

