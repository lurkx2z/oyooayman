/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if sound travelled faster than light?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/sound-faster-light/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions (and so does the story clock: which second after 2:40 PM we are watching), so changing a
   pause or a line here re-times the whole film. Writes timing.js (window.SFT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture or the sound is the reveal (the dark, the heat view, the grab, the fire, the crash, the car).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const PAUSE = {
  title: 0.05, start: 0.9, flash: 1.4, rule: 1.0, rumble: 2.2, call: 1.6, answer: 2.0, ears: 1.2, head: 1.6, far: 1.6, siren: 2.2, wind: 1.8,
  tornado: 2.6, phone: 1.6, corn: 1.8, strike: 1.8, neighbour: 2.2, found: 1.3, back: 1.6, question: 1.6,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.4, 'start:2': 0.4, 'flash:1': 0.8, 'flash:2': 0.6, 'rule:1': 0.4, 'rumble:1': 0.6, 'rumble:2': 1.0, 'call:1': 1.4,
  'answer:1': 1.0, 'ears:1': 0.6, 'ears:2': 0.6, 'head:1': 0.8, 'head:2': 1.0, 'siren:1': 1.4, 'siren:2': 0.8,
  'tornado:1': 0.6, 'tornado:2': 1.0, 'phone:1': 1.2, 'phone:2': 0.8, 'corn:1': 1.2, 'strike:1': 0.6, 'strike:2': 0.6, 'neighbour:1': 0.8,
  'found:1': 1.0, 'far:1': 0.8, 'far:2': 0.8, 'phone:3': 0.6, 'corn:2': 1.4, 'wind:1': 1.0, 'back:1': 1.0, 'back:2': 0.8,
};
const SECTION_OF = { title: 1, siren: 2, phone: 3 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = 1.6;                    // the question holds 3 s on black, then a hard cut (round 2: it went by too fast)
const hold = (s) => Math.min(5.4, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const SFT = { duration: r3(t + TAIL), groups };
{ const g = groups[groups.length - 1], c = g.caps[g.caps.length - 1]; c.hide = g.end = SFT.duration; }   // (the question stays up to the last frame)
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if sound travelled faster than light?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.SFT = ${JSON.stringify(SFT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${SFT.duration} s (${Math.floor(SFT.duration / 60)}:${String(Math.round(SFT.duration % 60)).padStart(2, '0')})`);
