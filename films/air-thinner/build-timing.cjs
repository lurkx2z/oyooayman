/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if the air got 1% thinner every minute?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/air-thinner/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions (and so does the story clock: which second after 10:00 AM we are watching), so changing a
   pause or a line here re-times the whole film. Writes timing.js (window.ATT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture or the sound is the reveal (the first tick, the balloon, the smoke, the blackout, the dive, the boil).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 0.8
const PAUSE = {
  title: 0.05, start: 0.4, weight: 1.0, boil: 1.0, ears: 1.4, storm: 2.4, cabin: 1.4, stairs: 1.4, tanks: 1.4, down: 1.4, engines: 2.6,
  marina: 1.4, dive: 1.2, under: 4.2, fizz: 1.4, shark: 2.0, everest: 2.0, oxygen: 1.4, rise: 1.6, sky: 1.8, tubs: 3.0, stars: 3.0, sea: 2.8, last: 1.6, question: 2.2,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.6, 'start:2': 0.3, 'weight:1': 0.4, 'weight:2': 0.6, 'boil:1': 0.8, 'ears:1': 1.4, 'storm:1': 0.8, 'cabin:1': 0.6, 'cabin:2': 1.0,
  'stairs:1': 0.8, 'stairs:2': 0.6, 'tanks:1': 0.6, 'tanks:2': 0.6, 'tanks:3': 0.4, 'down:1': 1.0, 'down:2': 0.8, 'engines:1': 3.0, 'fizz:1': 0.6, 'shark:1': 1.4, 'shark:2': 1.6,
  'marina:1': 0.8, 'marina:2': 0.6, 'dive:1': 1.0, 'under:1': 1.2, 'under:2': 1.0, 'everest:1': 1.2, 'rise:1': 0.8, 'rise:2': 1.2,
  'tubs:1': 1.4, 'tubs:2': 0.8, 'stars:1': 1.0, 'sea:1': 3.0, 'sea:2': 1.0, 'last:1': 1.2,
};
const SECTION_OF = { title: 1, tanks: 2, under: 3 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = 1.6;                    // the question holds 3 s on black, then a hard cut (round 2: it went by too fast)
const hold = (s) => Math.min(5.4, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const ATT = { duration: r3(t + TAIL), groups };
{ const g = groups[groups.length - 1], c = g.caps[g.caps.length - 1]; c.hide = g.end = ATT.duration; }   // (the question stays up to the last frame)
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if the air got 1% thinner every minute?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.ATT = ${JSON.stringify(ATT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${ATT.duration} s (${Math.floor(ATT.duration / 60)}:${String(Math.round(ATT.duration % 60)).padStart(2, '0')})`);
