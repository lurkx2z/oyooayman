/* =====================================================================
   BUILD-COLUMN — the sky coming down, computed once (node films/liquid-air/build-column.cjs → column.js).
   One column of the atmosphere, 1-D, metres and seconds, story time s = seconds after 3:00:00 PM:
   - THE RULE: from s = 0 to 600 each layer turns 1/(600 − s) of its gas left per second (the same amount, 1/600 of
     the original, every second), so the fraction
     of the air turned is f = s / 600 (all of it by 3:10:00). The liquid: 875 kg/m³ (liquid air's density).
   - each new bit of liquid is a drop where it formed; it falls with drag in the gas left there: terminal speed
     v0 · √(ρ0 / ρ_gas) (v0 = 5 m/s at sea level: a ~2 mm drop of a liquid lighter than water, with less surface tension)
   - the gas stays in balance: it carries its own weight AND the drag of every drop falling through it, so the
     pressure at the ground stays near 1 atm while the rain is up there, and the gas is squeezed into a thinner layer
   - when the gas is gone (3:10:00) nothing holds the rain up: it falls freely.
   Writes LA_COL: per story second 0…900: depth (m of liquid on the ground), p0 (gas pressure at the ground, atm),
   up (share of the air that is liquid still in the sky), v (mean speed of what lands in that second, m/s), and the
   headline numbers. Deterministic (fixed steps, no randomness). Honest limits: PLAN.md § 2.
   ===================================================================== */
const fs = require('fs'), path = require('path');
const g = 9.81, RT = 287 * 288, P0 = 101325, M = P0 / g, rhoL = 875, v0 = 5, T = 600, rho0 = P0 / RT;
const D = P0 / (rhoL * g);                       // the final depth: the weight of the whole sky as liquid (11.80 m)
const NZ = 300, ZT = 60000, dz = ZT / NZ, dt = 0.1, SEND = 900, SPAWN = 10;   // (new drops are gathered into one parcel per layer every second)
let parcels = [], landed = 0;
const pz = new Float64Array(NZ + 1), rg = new Float64Array(NZ + 1);
for (let i = 0; i <= NZ; i++) { pz[i] = P0 * Math.exp(-i * dz * g / RT); rg[i] = pz[i] / RT; }
const out = { depth: [], p0: [], up: [], v: [] };
let accM = 0, accMV = 0;
for (let k = 0; k <= SEND / dt; k++) {
  const t = k * dt, f = Math.min(1, t / T), fPrev = Math.min(1, (t - SPAWN * dt) / T), G = (1 - f) * M;
  if (k > 0 && k % SPAWN === 0 && f > fPrev) { const q = (f - fPrev) / (1 - fPrev); for (let i = 0; i < NZ; i++) { const m = rg[i] * dz * q; if (m > 1e-7) parcels.push({ z: (i + 0.5) * dz, v: 0, m }); } }
  const d = new Float64Array(NZ + 1); let Dtot = 0;
  for (const p of parcels) {
    const i = Math.min(NZ - 1, Math.floor(p.z / dz)), vt = v0 * Math.sqrt(rho0 / Math.max(1e-12, rg[i]));
    const r = Math.min(4, (p.v / vt) ** 2), F = p.m * g * Math.min(1, r);
    d[i] += F / dz; Dtot += F;
    p.v += g * (1 - r) * dt; if (r > 1) p.v = Math.max(vt, p.v - g * (r - 1) * dt);
    p.z -= p.v * dt;
    if (p.z <= 0) { landed += p.m; accM += p.m; accMV += p.m * p.v; p.dead = 1; }
  }
  parcels = parcels.filter((p) => !p.dead);
  // the gas: p(0) = its weight + the drag it carries; integrate up, then scale its mass back to G
  pz[0] = G * g + Dtot;
  for (let i = 1; i <= NZ; i++) pz[i] = Math.max(0, pz[i - 1] * Math.exp(-g * dz / RT) - d[i - 1] * dz);
  let gm = 0; for (let i = 0; i < NZ; i++) gm += (pz[i] / RT) * dz;
  for (let i = 0; i <= NZ; i++) rg[i] = gm > 0 ? (pz[i] / RT) * G / gm : 0;
  if (k % 10 === 0) {
    out.depth.push(+(landed / M * D).toFixed(4)); out.p0.push(+(f >= 1 ? 0 : pz[0] / P0).toFixed(4));
    out.up.push(+((f * M - landed) / M).toFixed(4)); out.v.push(accM > 0 ? Math.round(accMV / accM) : 0); accM = 0; accMV = 0;
  }
}
// (about 1 % of the mass is lost in the layer bookkeeping at this resolution: scale the landed depth so it ends at D)
{ const k = D / out.depth[out.depth.length - 1]; out.depth = out.depth.map((x) => +(x * k).toFixed(4)); out.up = out.up.map((x, i) => +Math.max(0, Math.min(i, 600) / 600 - out.depth[i] / D).toFixed(4)); }
// smooth p0 (the gas layer's balance wobbles a little at this resolution): a centred 5 s mean
const sm = out.p0.map((_, i) => { let a = 0, n = 0; for (let j = i - 2; j <= i + 2; j++) if (j >= 0 && j < out.p0.length) { a += out.p0[j]; n++; } return +(a / n).toFixed(4); });
sm[600] = 0; for (let i = 600; i < sm.length; i++) sm[i] = 0;
out.p0 = sm;
const firstAt = (arr, fn) => arr.findIndex(fn);
const head = {
  D: +D.toFixed(3), rhoL, v0, T,
  sCrash: [600, firstAt(out.depth, (x) => x > D - 0.15)],             // 3:10:00 → the sky is down
  vCrash: Math.round(out.v.slice(600, 615).reduce((a, x, i) => a + x * (out.depth[601 + i] - out.depth[600 + i]), 0) / (out.depth[615] - out.depth[600])),
};
const js = `/* The sky coming down: generated by build-column.cjs (do not edit by hand). Per story second s = 0…${SEND}. */\nwindow.LA_COL = ${JSON.stringify(Object.assign(head, out))};\n`;
fs.writeFileSync(path.join(__dirname, 'column.js'), js);
const mm = (s) => `3:${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
for (const s of [10, 30, 60, 120, 180, 240, 300, 360, 420, 480, 510, 540, 555, 570, 580, 590, 595, 600, 602, 604, 606, 608, 610, 612, 615, 620, 640, 660, 700, 800])
  console.log(mm(s), 'depth', out.depth[s].toFixed(2), 'm · p0', out.p0[s].toFixed(3), 'atm · still up', (out.up[s] * 100).toFixed(1), '% · landing at', out.v[s], 'm/s');
console.log({ D: head.D, sCrash: head.sCrash, vCrash: head.vCrash });
