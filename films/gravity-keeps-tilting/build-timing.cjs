/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if gravity kept tilting sideways every second and
   couldn't stop?" (voiceless: captions and sound only).
     node films/gravity-keeps-tilting/build-timing.cjs
   Reads CAPTIONS.md. The story clock runs at real speed (film t = story s + T0), so a beat is pinned to the angle it
   talks about: "[id @s]" shows its first caption at story second s; inside a beat each caption holds for hold(chars) and
   the next follows after GAP (or at its own "@s"); a beat without @ follows the last after PAUSE. A beat that would
   start before the last one has gone is an error (move its @). Writes timing.js (window.GKT). Pure data.
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const T0 = 1.0;                      // film t of story s = 0 (4:00:00 PM); the first tick is at s = 1
const PAUSE = 0.8;                   // before a beat with no @
const GAP = 0.6;                     // between captions inside a beat
const TAIL = 2.6;                    // the question's time on screen before the hard cut (nothing signals the end)
const hold = (s) => Math.min(4.2, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE = [0.05, 3.15];           // the title card: from, for
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+/.test(p)).map((p, k) => {
  const m = /^\[([\w-]+)(?:\s+@([\d.]+))?\]\s*([\s\S]*)$/.exec(p);
  return { id: m[1], n: k + 1, at: m[2] == null ? null : +m[2], caps: m[3].replace(/\s+/g, ' ').trim().split(' / ') };
});
const groups = [], ERR = [];
let t = 0;
for (const B of beats) {
  let c0 = B.id === 'title' ? TITLE[0] : B.at != null ? r3(B.at + T0) : r3(t + PAUSE);
  if (groups.length && c0 < t + 0.3) { ERR.push(`[${B.id}] @${B.at} starts before the last beat has gone: earliest @${(t + 0.3 - T0).toFixed(1)}`); c0 = r3(t + 0.3); }
  const caps = [];
  B.caps.forEach((s0, i) => {
    let s = s0;
    const m = /^@([\d.]+)\s+(.*)$/.exec(s0);
    // (a caption pinned to its own second cuts the one before it short, to no less than 0.85 s)
    if (m) { const at = r3(+m[1] + T0), pv = caps[i - 1]; if (pv && at - 0.15 < pv.show + 0.85) ERR.push(`[${B.id}] caption ${i} pinned too soon after the one before`); if (pv) pv.hide = Math.min(pv.hide, r3(at - 0.15)); c0 = at; s = m[2]; }
    const d = B.id === 'title' ? TITLE[1] : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    caps.push(cap);
  });
  const g = { id: B.id, n: B.n, at: B.at, title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
}
if (ERR.length) { console.log(ERR.join('\n')); process.exit(1); }
const GKT = { t0: T0, duration: r3(t + TAIL - hold(groups[groups.length - 1].caps.slice(-1)[0].text) + 0.0), groups };
GKT.duration = r3(groups[groups.length - 1].caps.slice(-1)[0].show + TAIL);
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if gravity kept tilting sideways every second and couldn't stop?", generated by
   build-timing.cjs from CAPTIONS.md. Do not edit by hand: change the captions there and re-run it. */
window.GKT = ${JSON.stringify(GKT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)} (${String(Math.floor(g.first - T0)).padStart(3)}°)  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${GKT.duration} s (${Math.floor(GKT.duration / 60)}:${String(Math.round(GKT.duration % 60)).padStart(2, '0')})`);
