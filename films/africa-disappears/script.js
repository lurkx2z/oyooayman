const AN_CLIP = Object.fromEntries(AN.clips.map((c) => [c.n, c]));
// the first word of clip n (from word index `from`) that starts with `txt` (case and punctuation ignored)
function afW(n, txt, from = 0) {
  const k = txt.toLowerCase(), ws = AN_CLIP[n].words;
  for (let i = from; i < ws.length; i++) if (ws[i].text.toLowerCase().replace(/[^a-z0-9']/g, '').startsWith(k)) return ws[i];
  throw new Error(`afW: "${txt}" not found in clip ${n}`);
}
