/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if your shadow lagged 1 second behind you?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/shadow-lag/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions (and so does the story clock: which second after 11:58 PM we are watching), so changing a
   pause or a line here re-times the whole film. Writes timing.js (window.SHT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture itself is the reveal (the shadow staying behind, the hand, the walk into you, the shadow
   that keeps moving, the torch, the ramp, the camera, the back seat).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 0.8
const PAUSE = {
  title: 0.05, start: 0.6, only: 1.0, warn: 1.0, light: 1.6, hand: 1.4, walk: 1.6, stop: 1.4, turn: 1.4, mirror: 1.6, lamps: 1.6, impossible: 1.6,
  where: 1.6, midnight: 1.8, steps: 2.4, hide: 1.4, still: 1.4, moving: 1.8, guard: 2.2, seen: 1.6, run: 1.4, car: 2.0, speed: 2.0, cctv: 1.8,
  exit: 2.0, question: 5.0, film: 1.4, radio: 1.2, lock: 1.4, jump: 1.4,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.8, 'light:1': 0.6, 'light:2': 0.4, 'light:3': 0.6, 'hand:1': 1.4, 'hand:2': 1.0, 'walk:1': 1.0, 'stop:1': 1.2, 'mirror:1': 0.8, 'lamps:1': 1.2,
  'impossible:1': 0.8, 'impossible:2': 0.8, 'where:1': 0.6, 'where:2': 0.6, 'where:3': 0.8, 'midnight:1': 1.4, 'hide:1': 1.2, 'still:1': 0.8, 'still:2': 1.2,
  'moving:1': 2.4, 'guard:1': 1.6, 'guard:2': 1.6, 'seen:1': 1.4, 'run:2': 0.8, 'run:3': 0.6, 'car:1': 1.4, 'speed:1': 1.4, 'cctv:1': 1.0,
  'exit:1': 1.4, 'exit:2': 1.6, 'film:1': 1.6, 'jump:1': 1.2,
};
const SECTION_OF = { title: 1, midnight: 2, car: 3 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = -0.4;                   // a hard cut while the question is still on screen (nothing signals the end)
const hold = (s) => Math.min(4.2, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const SHT = { duration: r3(t + TAIL), groups };
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if your shadow lagged 1 second behind you?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.SHT = ${JSON.stringify(SHT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${SHT.duration} s (${Math.floor(SHT.duration / 60)}:${String(Math.round(SHT.duration % 60)).padStart(2, '0')})`);
