/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if days kept getting shorter and couldn\u2019t stop?"
   (voiceless, like the Slower light film: captions and sound only).
     node films/days-shorter/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. Every beat in script.js
   keys off these captions' words (each word gets an anchor time inside its caption), and so does the story clock (which
   of the ten seconds we are watching, and how slowly), so changing a pause or a line here re-times the whole film.
   Writes timing.js (window.DST). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture itself is the reveal (the strobing days, the sofa, the spire, the 9-second sunset, the last sunrise).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 0.8
const PAUSE = {
  title: 0.05, start: 0.6, math: 0.8, dish: 2.4, sunset: 3.0, real: 1.6, quake: 2.4, sunrise: 2.4, node: 1.8, birds: 3.0, midnight: 2.4,
  lamps: 2.4, wed: 3.0, scale: 2.0, push: 1.4, marble: 1.0, quake2: 2.2, pond: 2.8, car: 2.2, swings: 2.4, friday: 3.4, lighter: 2.2,
  jump: 2.8, glass: 2.2, sat: 2.6, slide: 2.4, spire: 2.6, lean: 2.6, cars: 3.2, equator: 3.0, sunset2: 5.0, stars: 4.5, dawn: 4.0, question: 3.4,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.4, 'real:1': 0.6, 'dish:1': 1.0, 'sunset:1': 2.0, 'quake:1': 2.0, 'sunrise:1': 2.2, 'node:1': 0.6, 'node:2': 0.6,
  'midnight:1': 2.0, 'scale:1': 0.8, 'push:1': 1.0, 'marble:1': 2.4, 'pond:1': 2.2, 'car:1': 2.8, 'swings:1': 2.0, 'friday:1': 4.0, 'lighter:1': 2.0,
  'glass:1': 2.0, 'sat:1': 1.0, 'slide:1': 2.4, 'spire:1': 4.0, 'equator:1': 0.8, 'dawn:1': 2.6, 'question:1': 1.4,
};
const SECTION_OF = { title: 1, midnight: 2, friday: 3, sat: 4 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = -0.5;                   // a hard cut while the question is still on screen (nothing signals the end)
const hold = (s) => Math.min(4.2, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const DST = { duration: r3(t + TAIL), groups };
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if days kept getting shorter and couldn\u2019t stop?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.DST = ${JSON.stringify(DST)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${DST.duration} s (${Math.floor(DST.duration / 60)}:${String(Math.round(DST.duration % 60)).padStart(2, '0')})`);
