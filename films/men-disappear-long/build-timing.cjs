/* =====================================================================
   BUILD-TIMING — the caption half of the master timeline for "What if all men suddenly disappeared?" (voiceless:
   captions and sound only).
     node films/men-disappear-long/build-timing.cjs
   Reads CAPTIONS.md and places every caption at reading pace: PAUSE[k] = the empty screen before beat k's first
   caption; inside a beat each caption holds for hold(chars) and the next follows after GAP. AFTER pins a beat's first
   caption to a fixed time after another caption (the cockpit door's 30 seconds run in real time). Every beat in
   script.js keys off these captions, and so does the story clock, so changing a pause or a line here re-times the film.
   Writes timing.js (window.MGT). Pure data: no clock, no randomness.
   Retention (the owner's playbook, 2026-10-28): no dead air, a new thing to see every few seconds; the long pauses are
   only where the picture itself is the reveal (the lorry, the viaduct, the door's count, the landing).
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
// empty screen before each beat's first caption (s); default 0.8
const PAUSE = {
  title: 0.05, start: 1.0, wheel: 1.0, brake: 1.0, lorry: 1.2, cab: 1.4, stop: 1.0, cars: 1.8, radio: 2.4, phone: 2.0, train: 2.8, barge: 2.6, plane: 2.8, world: 1.6,
  door: 2.6, alone: 1.0, tower: 2.8, smoke: 2.8, ward: 2.8, walk: 3.0, alert: 2.6, hold: 3.0, many: 2.2, autoland: 2.4, final: 2.8, question: 2.6,
};
// extra empty screen before one caption inside a beat: 'beat:index' → s (where the picture itself is the reveal)
const EXTRA = {
  'start:1': 0.6, 'wheel:1': 0.6, 'brake:1': 0.8, 'lorry:1': 1.6, 'cab:1': 0.8, 'cars:1': 1.0, 'cars:2': 1.0, 'radio:1': 0.8, 'phone:1': 1.0,
  'train:1': 1.0, 'barge:1': 2.4, 'plane:1': 1.0, 'plane:2': 1.0, 'world:1': 0.8, 'door:1': 0.6, 'door:2': 4.0, 'door:3': 3.0, 'alone:1': 1.0,
  'tower:1': 1.0, 'smoke:1': 1.0, 'smoke:2': 0.8, 'ward:1': 0.8, 'ward:2': 2.4, 'ward:3': 1.2, 'ward:4': 1.6, 'walk:1': 1.0, 'walk:2': 1.2,
  'alert:1': 0.8, 'alert:2': 0.8, 'many:1': 0.8, 'many:2': 0.8, 'autoland:1': 0.8, 'autoland:2': 1.0, 'autoland:3': 2.0, 'final:1': 3.6, 'final:2': 7.7, 'final:3': 4.0, 'final:4': 3.3, 'question:1': 1.0,
};
// a beat whose first caption must come a fixed time after another caption shows: beat → [beat, caption, seconds]
const AFTER = { alone: ['door', 1, 31.0] };
const SECTION_OF = { title: 1, radio: 2, smoke: 3, walk: 4 };
const GAP = 0.6;                     // between captions inside a beat
const TAIL = -0.4;                   // a hard cut while the question is still on screen (nothing signals the end)
const hold = (s) => Math.min(4.2, Math.max(1.5, 1.0 + 0.05 * s.length));
const TITLE_HOLD = 3.3;
const r3 = (x) => Math.round(x * 1000) / 1000;

const text = fs.readFileSync(path.join(DIR, 'CAPTIONS.md'), 'utf8').replace(/^---[\s\S]*?\n---\n/, '');
const beats = text.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^\[[\w-]+\]/.test(p))
  .map((p, k) => { const m = /^\[([\w-]+)\]\s*([\s\S]*)$/.exec(p); return { id: m[1], n: k + 1, caps: m[2].replace(/\s+/g, ' ').trim().split(' / ') }; });
for (const k of Object.keys(PAUSE)) if (!beats.find((b) => b.id === k)) throw new Error('PAUSE: no beat ' + k);
for (const k of Object.keys(EXTRA)) { const [id, i] = k.split(':'); const B = beats.find((b) => b.id === id); if (!B || !B.caps[+i]) throw new Error('EXTRA: no caption ' + k); }
let sec = 0; const SECTION = beats.map((b) => (sec = SECTION_OF[b.id] || sec));

const groups = [];
let t = 0;
beats.forEach((B, k) => {
  let c0 = r3(t + (PAUSE[B.id] ?? 0.8));
  if (AFTER[B.id]) { const [bid, ci, d] = AFTER[B.id], G = groups.find((g) => g.id === bid); c0 = Math.max(c0, r3(G.caps[ci].show + d)); }
  const caps = B.caps.map((s, i) => {
    c0 = r3(c0 + (EXTRA[B.id + ':' + i] || 0));
    const d = B.id === 'title' ? TITLE_HOLD : hold(s), ws = s.split(' ');
    const cap = { text: s, show: c0, hide: r3(c0 + d), words: ws.map((w, j) => ({ text: w, start: r3(c0 + 0.7 * d * j / ws.length) })) };
    c0 = r3(c0 + d + GAP);
    return cap;
  });
  const g = { id: B.id, n: B.n, section: SECTION[k], title: B.id === 'title', first: caps[0].show, end: caps[caps.length - 1].hide, caps };
  groups.push(g);
  t = g.end;
});
const MGT = { duration: r3(t + TAIL), groups };
fs.writeFileSync(path.join(DIR, 'timing.js'), `/* Caption timing for "What if all men suddenly disappeared?", generated by build-timing.cjs from CAPTIONS.md.
   Do not edit by hand: change the captions or PAUSE/GAP/TAIL there and re-run it. */
window.MGT = ${JSON.stringify(MGT)};
`);
const mmss = (x) => `${Math.floor(x / 60)}:${(x % 60).toFixed(1).padStart(4, '0')}`;
for (const g of groups) console.log(`${String(g.n).padStart(2)} ${mmss(g.first).padStart(7)} → ${mmss(g.end).padStart(7)}  [${g.id}] ${g.caps.map((c) => c.text).join(' / ')}`);
console.log(`${groups.reduce((n, g) => n + g.caps.length, 0)} captions · film ${MGT.duration} s (${Math.floor(MGT.duration / 60)}:${String(Math.round(MGT.duration % 60)).padStart(2, '0')})`);
